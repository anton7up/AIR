const priorityKeywords: Record<string, string[]> = {
  after_meal: ["зуб", "жвач", "вод", "тарел", "стол"], coffee: ["вод", "жвач", "чаш", "пройд"],
  before_sleep: ["зуб", "травя", "вод", "тёпл"],
};

export function replacementActions(focus: ReplacementFocus, trigger: string | null): StepOption[] {
  if (trigger === "driving") return SAFE_DRIVING_REPLACEMENTS[focus];
  let pool = REPLACEMENT_ACTIONS[focus];
  if (trigger === "coffee" || trigger === "before_sleep") {
    pool = pool.filter(item => !item.label.toLocaleLowerCase("ru-RU").includes("кофе"));
  }
  const keywords = trigger ? priorityKeywords[trigger] ?? [] : [];
  if (!keywords.length) return pool;
  return [...pool].sort((left, right) => Number(matchesPriority(right, keywords)) - Number(matchesPriority(left, keywords)));
}

function matchesPriority(action: StepOption, keywords: string[]) {
  const label = action.label.toLocaleLowerCase("ru-RU");
  return keywords.some(keyword => label.includes(keyword));
}

export function switchActions(trigger: string | null): StepOption[] {
  const contextual = trigger ? CONTEXT[trigger] ?? [] : [];
  if (trigger === "driving") return contextual;
  return [...contextual, ...UNIVERSAL].filter((item, index, all) => all.findIndex(candidate => candidate.id === item.id) === index);
}

export function nextAction(pool: StepOption[], history: string[]): StepOption {
  const recent = new Set(history.slice(-5));
  return pool.find(item => !history.includes(item.id)) ?? pool.find(item => !recent.has(item.id)) ?? pool[0];
}

export function recordAction(history: string[], id: string): string[] {
  return [...history.filter(item => item !== id), id];
}
